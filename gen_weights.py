"""Generate weights.h from the weights exported to ai_puro.py.

Usage: python gen_weights.py ../ai_puro.py weights.h
The arrays are read as data (ast.literal_eval); ai_puro.py is never executed.
"""
import ast
import re
import sys

NAMES = ["W1", "B1", "W2", "B2", "W3", "B3"]


def load(path):
    src = open(path, encoding="utf-8").read()
    arrays = {}
    for name in NAMES:
        match = re.search(rf"^{name} = (.*)$", src, re.M)
        if not match:
            sys.exit(f"{name} not found in {path}")
        arrays[name] = ast.literal_eval(match.group(1))
    return arrays


def fmt(v):
    return repr(float(v)) + "f"


def main(src, dst):
    a = load(src)
    n_in, n_h1 = len(a["W1"]), len(a["W1"][0])
    n_h2, n_out = len(a["W2"][0]), len(a["W3"][0])
    lines = [
        "// Generated by gen_weights.py from ai_puro.py - do not edit by hand.",
        "#pragma once",
        "",
        f"constexpr int N_INPUT = {n_in};",
        f"constexpr int N_HIDDEN1 = {n_h1};",
        f"constexpr int N_HIDDEN2 = {n_h2};",
        f"constexpr int N_OUTPUT = {n_out};",
        "",
    ]
    for name in NAMES:
        v = a[name]
        if isinstance(v[0], list):
            rows = ",\n".join("    {" + ", ".join(fmt(x) for x in r) + "}" for r in v)
            lines.append(f"static const float {name}[{len(v)}][{len(v[0])}] = {{\n{rows}\n}};\n")
        else:
            lines.append(f"static const float {name}[{len(v)}] = {{{', '.join(fmt(x) for x in v)}}};\n")
    open(dst, "w", encoding="utf-8").write("\n".join(lines))
    print(f"{dst}: {n_in} -> {n_h1} -> {n_h2} -> {n_out}")


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2])
